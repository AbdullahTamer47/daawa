// Calculate Day of the Year (1 to 366)
export function getDayOfYear(date = new Date()) {
    const start = new Date(date.getFullYear(), 0, 0);
    const diff = (date - start) + ((start.getTimezoneOffset() - date.getTimezoneOffset()) * 60 * 1000);
    const oneDay = 1000 * 60 * 60 * 24;
    return Math.floor(diff / oneDay);
}

// 365-Day Resolver
export function getDailyContentForDate(date = new Date()) {
    // If Friday (day 5), give priority to Friday virtues
    if (date.getDay() === 5) {
        return FRIDAY_CONTENT;
    }

    const dayOfYear = getDayOfYear(date);
    const index = (dayOfYear - 1) % BASE_HADITHS_AND_DUAS.length;
    return {
        ...BASE_HADITHS_AND_DUAS[index],
        dayNumber: dayOfYear,
    };
}

